#[cfg(test)]
mod tests {
    use super::resolve;

    #[test]
    fn regional_affiliates_and_independent_stations() {
        for (sid, expected) in [
            (1040, 4),   // Nippon TV
            (2088, 4),   // Yomiuri TV
            (1048, 6),   // TBS
            (2064, 6),   // MBS
            (2072, 5),   // ABC
            (2080, 8),   // Kansai TV
            (10264, 4),  // Sapporo TV
            (56360, 7),  // TVQ Kyushu
            (42032, 14), // KBS Kyoto
            (43056, 13), // Sun TV
        ] {
            assert_eq!(resolve(0x7880, sid), Some(expected), "SID {sid}");
        }
    }

    #[test]
    fn subchannels_boundaries_and_unknown_ids() {
        for nid in [0x7880, 0x7fef] {
            assert_eq!(resolve(nid, 1025), Some(1));
            assert_eq!(resolve(nid, 1034), Some(2));
            assert_eq!(resolve(nid, 2089), Some(4));
            assert_eq!(resolve(nid, 2090), Some(4));
            assert_eq!(resolve(nid, 2091), None);
            assert_eq!(resolve(nid, 23610), Some(9));
            for sid in [0, 1, 2, 999, u16::MAX] {
                assert_eq!(resolve(nid, sid), None);
            }
        }
        for nid in [15, 0x787f, 0x7ff0, u16::MAX] {
            assert_eq!(resolve(nid, 1040), None);
        }
    }

    #[test]
    fn satellite_requires_known_network_and_service_pair() {
        for (nid, sid, expected) in [
            (4, 102, Some(101)),
            (4, 142, Some(141)),
            (4, 143, Some(141)),
            (4, 144, None),
            (4, 263, Some(200)),
            (11, 101, Some(103)),
            (7, 333, Some(333)),
            (4, 333, None),
            (7, 101, None),
            (0, 101, None),
        ] {
            assert_eq!(resolve(nid, sid), expected);
        }
    }
}
